import api from "../../api";


const commentService = {

    /*
    |--------------------------------------------------------------------------
    | Get Admin Comments
    |--------------------------------------------------------------------------
    */

    getAdminComments(params = {}) {

        return api.get(
            "/comments/admin/all",
            {
                params,
            }
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Get Comment Statistics
    |--------------------------------------------------------------------------
    */

    getCommentStatistics() {

        return api.get(
            "/comments/admin/statistics"
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Get Single Comment
    |--------------------------------------------------------------------------
    */

    getComment(id) {

        return api.get(
            `/comments/${id}`
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Approve Comment
    |--------------------------------------------------------------------------
    */

    approveComment(id) {

        return api.patch(
            `/comments/admin/${id}/approve`
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Reject Comment
    |--------------------------------------------------------------------------
    */

    rejectComment(id) {

        return api.patch(
            `/comments/admin/${id}/reject`
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Move To Pending
    |--------------------------------------------------------------------------
    */

    moveToPending(id) {

        return api.patch(
            `/comments/admin/${id}/pending`
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Mark As Spam
    |--------------------------------------------------------------------------
    */

    markSpam(id) {

        return api.patch(
            `/comments/admin/${id}/spam`
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Restore Comment
    |--------------------------------------------------------------------------
    */

    restoreComment(id) {

        return api.patch(
            `/comments/admin/${id}/restore`
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Delete Comment
    |--------------------------------------------------------------------------
    */

    deleteComment(id) {

        return api.delete(
            `/comments/admin/${id}`
        );

    },

    /*
    |--------------------------------------------------------------------------
    | Delete Reply
    |--------------------------------------------------------------------------
    */

    deleteReply(replyId) {

        return api.delete(
            `/comments/replies/${replyId}`
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Reply To Comment
    |--------------------------------------------------------------------------
    */

    replyComment(id, data) {

        return api.post(
            `/comments/admin/${id}/reply`,
            data
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Get Comment Reports
    |--------------------------------------------------------------------------
    */

    getCommentReports(id) {

        return api.get(
            `/comments/admin/${id}/reports`
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Get Replies
    |--------------------------------------------------------------------------
    */

    getReplies(id) {

        return api.get(
            `/comments/${id}/replies`
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Bulk Approve
    |--------------------------------------------------------------------------
    */

    bulkApprove(commentIds) {

        return api.post(
            "/comments/admin/bulk/approve",
            {
                ids: commentIds,
            }
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Bulk Reject
    |--------------------------------------------------------------------------
    */

    bulkReject(commentIds) {

        return api.post(
            "/comments/admin/bulk/reject",
            {
                ids: commentIds,
            }
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Bulk Mark As Spam
    |--------------------------------------------------------------------------
    */

    bulkSpam(commentIds) {

        return api.post(
            "/comments/admin/bulk/spam",
            {
                ids: commentIds,
            }
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Bulk Restore
    |--------------------------------------------------------------------------
    */

    bulkRestore(commentIds) {

        return api.post(
            "/comments/admin/bulk/restore",
            {
                ids: commentIds,
            }
        );

    },


    /*
    |--------------------------------------------------------------------------
    | Bulk Delete
    |--------------------------------------------------------------------------
    */

    bulkDelete(commentIds) {

        return api.post(
            "/comments/admin/bulk/delete",
            {
                ids: commentIds,
            }
        );

    },

};


export default commentService;
